/**
 * src/services/manifest-generator.js — Kubernetes manifest generator
 *
 * This is where the Ollama model provisioning magic happens.
 *
 * Given deployment parameters (model name, resource limits, replicas),
 * this module generates a complete Kubernetes YAML manifest containing:
 *
 *   1. A Deployment with:
 *      - An initContainer ("pull-model") that runs `ollama pull <model>`
 *        to download the model weights to the shared PVC
 *      - A main container ("ollama-server") that runs `ollama serve`
 *        to serve the inference API on port 11434
 *      - Volume mounts to shared-models-pvc
 *      - Resource requests/limits from user input
 *      - Liveness and readiness probes on /api/tags
 *
 *   2. A Service (NodePort) that exposes the Ollama API externally
 *
 * The YAML is returned as a string. The caller writes it to the Git repo.
 */

/**
 * Generate a complete Kubernetes manifest for an Ollama model deployment.
 *
 * @param {Object} params
 * @param {string} params.deploymentId   - Unique deployment ID (e.g., "deploy-1710834567890-a1b2c3")
 * @param {string} params.modelName      - Ollama model name (e.g., "llama2")
 * @param {string} params.cpuRequest     - CPU request (e.g., "2000m")
 * @param {string} params.cpuLimit       - CPU limit (e.g., "4000m")
 * @param {string} params.memoryRequest  - Memory request (e.g., "4Gi")
 * @param {string} params.memoryLimit    - Memory limit (e.g., "8Gi")
 * @param {number} params.replicas       - Number of pod replicas
 * @param {string} params.namespace      - Kubernetes namespace (e.g., "user-1")
 * @returns {string} Complete YAML manifest (Deployment + Service)
 */
function generate(params) {
  const {
    deploymentId,
    modelName,
    cpuRequest,
    cpuLimit,
    memoryRequest,
    memoryLimit,
    replicas,
    namespace,
  } = params;

  // The service name is the deployment ID with a -svc suffix
  const serviceName = `${deploymentId}-svc`;

  return `# Auto-generated by ML Platform Backend
# Deployment: ${deploymentId}
# Model: ${modelName}
# Generated: ${new Date().toISOString()}
---
apiVersion: v1
kind: Namespace
metadata:
  name: ${namespace}
---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: ${deploymentId}
  namespace: ${namespace}
  labels:
    app: ${deploymentId}
    model: ${modelName}
    managed-by: ml-platform
spec:
  replicas: ${replicas}
  selector:
    matchLabels:
      app: ${deploymentId}
  template:
    metadata:
      labels:
        app: ${deploymentId}
        model: ${modelName}
    spec:
      # Use Docker Hub credentials to pull the Ollama image
      imagePullSecrets:
        - name: dockerhub-secret

      # Prefer scheduling on the worker node (where the bulk of RAM is)
      affinity:
        nodeAffinity:
          preferredDuringSchedulingIgnoredDuringExecution:
            - weight: 100
              preference:
                matchExpressions:
                  - key: kubernetes.io/hostname
                    operator: In
                    values:
                      - rke2-worker

      # ---------------------------------------------------------------
      # initContainer: Downloads the model BEFORE the main container starts.
      #
      # How it works:
      #   1. Starts the ollama/ollama:latest image
      #   2. Runs "ollama serve" in the background (needed for the pull command)
      #   3. Waits 5 seconds for the server to start
      #   4. Runs "ollama pull ${modelName}" which contacts registry.ollama.ai
      #      and downloads the model weights in GGUF format
      #   5. Model files are saved to /root/.ollama/models/ (on the PVC)
      #   6. If the model already exists on the PVC (from a previous deployment),
      #      the pull is a no-op and completes instantly
      #   7. Container exits with code 0
      # ---------------------------------------------------------------
      initContainers:
        - name: pull-model
          image: ollama/ollama:latest
          command:
            - /bin/sh
            - -c
            - |
              echo "Starting Ollama server for model pull..."
              ollama serve &
              sleep 5
              echo "Pulling model: ${modelName}..."
              ollama pull ${modelName}
              echo "Model pull complete."
          volumeMounts:
            - name: model-storage
              mountPath: /root/.ollama
          resources:
            requests:
              cpu: "500m"
              memory: "512Mi"
            limits:
              cpu: "${cpuLimit}"
              memory: "${memoryLimit}"

      # ---------------------------------------------------------------
      # Main container: Serves the model inference API.
      #
      # How it works:
      #   1. Starts the ollama/ollama:latest image
      #   2. Runs "ollama serve" which starts an HTTP server on port 11434
      #   3. Mounts the same PVC as the initContainer, so it sees the
      #      downloaded model files immediately
      #   4. Ollama detects the model, memory-maps the GGUF file into RAM
      #   5. Serves endpoints: /api/generate, /api/chat, /api/tags
      #   6. Readiness probe hits /api/tags every 10s — once it returns
      #      200 OK, the pod is marked Ready and receives traffic
      # ---------------------------------------------------------------
      containers:
        - name: ollama-server
          image: ollama/ollama:latest
          command: ["ollama", "serve"]
          ports:
            - containerPort: 11434
              name: ollama
              protocol: TCP
          env:
            - name: OLLAMA_HOST
              value: "0.0.0.0:11434"
            - name: OLLAMA_MODELS
              value: "/root/.ollama/models"
          volumeMounts:
            - name: model-storage
              mountPath: /root/.ollama
          resources:
            requests:
              cpu: "${cpuRequest}"
              memory: "${memoryRequest}"
            limits:
              cpu: "${cpuLimit}"
              memory: "${memoryLimit}"

          # Readiness probe: is the server ready to accept requests?
          # Checks /api/tags which returns a list of loaded models.
          # Initial delay gives the server time to start and load the model.
          readinessProbe:
            httpGet:
              path: /api/tags
              port: 11434
            initialDelaySeconds: 30
            periodSeconds: 10
            timeoutSeconds: 10
            failureThreshold: 6

          # Liveness probe: is the server still alive?
          # If this fails 3 times, Kubernetes restarts the container.
          livenessProbe:
            httpGet:
              path: /api/tags
              port: 11434
            initialDelaySeconds: 60
            periodSeconds: 30
            timeoutSeconds: 10
            failureThreshold: 3

      # ---------------------------------------------------------------
      # Volume: The shared PVC where all model files are stored.
      # All Ollama pods mount this same PVC, so models are shared.
      # First download of a model writes to the PVC; subsequent pods
      # find the model already there and skip the download.
      # ---------------------------------------------------------------
      volumes:
        - name: model-storage
          persistentVolumeClaim:
            claimName: shared-models-pvc
---
apiVersion: v1
kind: Service
metadata:
  name: ${serviceName}
  namespace: ${namespace}
  labels:
    app: ${deploymentId}
    model: ${modelName}
    managed-by: ml-platform
spec:
  type: NodePort
  selector:
    app: ${deploymentId}
  ports:
    - port: 11434
      targetPort: 11434
      protocol: TCP
      name: ollama
`;
}

module.exports = { generate };
